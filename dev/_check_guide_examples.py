# 目的：把 content-guide.js 里的 R 代码块抽出来，逐段交给 R 实跑，验证「复制即可运行」
# 输入：docs/assets/js/content-guide.js
# 输出：dev/_audit/guide_blocks/block_XX.R + dev/_audit/guide_runner.R
# 用法：python dev/_check_guide_examples.py && Rscript dev/_audit/guide_runner.R

import html
import pathlib
import re

SRC = pathlib.Path("docs/assets/js/content-guide.js")
OUT_DIR = pathlib.Path("dev/_audit/guide_blocks")
RUNNER = pathlib.Path("dev/_audit/guide_runner.R")

src = SRC.read_text(encoding="utf-8")
raw_blocks = re.findall(r'<pre><code class="language-r">(.*?)</code></pre>', src, re.S)


def clean(block: str) -> str:
    # 去掉 JS 字符串拼接缝：'...\n' +\n          '...'
    block = re.sub(r"'\s*\+\s*\n\s*'", "", block)
    block = block.strip()
    if block.startswith("'"):
        block = block[1:]
    if block.endswith("'"):
        block = block[:-1]
    block = block.replace("\\n", "\n").replace("\\t", "\t")
    return html.unescape(block)


blocks = [clean(b) for b in raw_blocks]
# 中文版在前、英文版在后且逻辑相同；只跑前半，避免 benchmark 重复执行
blocks = blocks[: len(blocks) // 2]

OUT_DIR.mkdir(parents=True, exist_ok=True)
for old in OUT_DIR.glob("block_*.R"):
    old.unlink()
for i, b in enumerate(blocks, 1):
    (OUT_DIR / f"block_{i:02d}.R").write_text(b + "\n", encoding="utf-8")

runner = """# Auto-generated by dev/_check_guide_examples.py -- do not edit by hand
Sys.setlocale('LC_CTYPE', 'en_US.UTF-8')
suppressMessages({
  library(mlr3); library(mlr3learners); library(dplyr); library(survival)
  pkgload::load_all('.', quiet = TRUE)
})
options(warn = -1)
failed <- character()
files <- sort(list.files('dev/_audit/guide_blocks', pattern = '^block_.*\\\\.R$', full.names = TRUE))
for (f in files) {
  cat('BLOCK', basename(f), '... ')
  ok <- tryCatch({ source(f, local = .GlobalEnv); TRUE },
                 error = function(e) { cat('FAIL:', conditionMessage(e), '\\n'); FALSE })
  if (isTRUE(ok)) cat('OK\\n') else failed <- c(failed, basename(f))
}
cat('FAILED:', if (length(failed)) paste(failed, collapse = ', ') else 'NONE', '\\n')
if (length(failed)) quit(status = 1)
"""
RUNNER.write_text(runner, encoding="utf-8")
print(f"blocks: {len(blocks)} -> {OUT_DIR} / {RUNNER}")
